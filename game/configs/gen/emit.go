package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

// generate 生成全部表的 Go 代码（*.gen.go）与 JSON 数据（data/*.json）。
func generate(outDir string, tables []*Table) error {
	if err := os.MkdirAll(filepath.Join(outDir, "data"), 0o755); err != nil {
		return err
	}
	seenTable := make(map[string]string)
	seenStruct := make(map[string]string)
	for _, t := range tables {
		if prev, dup := seenTable[t.Name]; dup {
			return fmt.Errorf("duplicate table name %q (also %s)", t.Name, prev)
		}
		seenTable[t.Name] = t.Name
		if prev, dup := seenStruct[t.StructName]; dup {
			return fmt.Errorf("duplicate struct name %q (also %s)", t.StructName, prev)
		}
		seenStruct[t.StructName] = t.Name

		code, err := emitTable(t)
		if err != nil {
			return fmt.Errorf("emit %s: %w", t.Name, err)
		}
		if err := os.WriteFile(filepath.Join(outDir, t.StructName+".gen.go"), code, 0o644); err != nil {
			return err
		}
		if err := writeTableData(outDir, t); err != nil {
			return err
		}
	}
	reg, err := emitRegistry(tables)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, "registry.gen.go"), reg, 0o644)
}

// emitTable 生成一张表的 Go 代码：行结构体 + 原子快照表 + 全局实例。
func emitTable(t *Table) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by game/configs/gen; DO NOT EDIT.\n\n")
	b.WriteString("package configs\n\n")
	b.WriteString("import (\n\t\"encoding/json\"\n\t\"fmt\"\n\t\"sync/atomic\"\n)\n\n")

	name := t.StructName
	data := unexport(name) + "Data"

	// 行结构体
	fmt.Fprintf(&b, "// %sRow %s\n", name, t.Comment)
	fmt.Fprintf(&b, "type %sRow struct {\n", name)
	for _, f := range t.ServerFields() {
		if f.Comment != "" {
			fmt.Fprintf(&b, "\t// %s\n", f.Comment)
		}
		fmt.Fprintf(&b, "\t%s %s `json:\"%s\"`\n", f.GoName, f.GoType, f.RawName)
	}
	b.WriteString("}\n\n")

	// 内部快照
	fmt.Fprintf(&b, "type %s struct {\n\tlist  []%sRow\n\tindex map[%s]int32\n}\n\n", data, name, t.KeyGoType())

	// 表类型
	fmt.Fprintf(&b, "// %sTable %s运行时表：Get/List/Len 读取原子快照。\n", name, t.Comment)
	fmt.Fprintf(&b, "type %sTable struct {\n\tp atomic.Pointer[%s]\n}\n\n", name, data)

	// Name
	fmt.Fprintf(&b, "// Name 返回表名。\n")
	fmt.Fprintf(&b, "func (t *%sTable) Name() string { return %q }\n\n", name, t.Name)

	// Decode
	fmt.Fprintf(&b, "// Decode 从 JSON 数组构建并原子替换快照；重复主键返回错误。\n")
	fmt.Fprintf(&b, "func (t *%sTable) Decode(raw []byte) error {\n", name)
	fmt.Fprintf(&b, "\tvar list []%sRow\n", name)
	fmt.Fprintf(&b, "\tif err := json.Unmarshal(raw, &list); err != nil {\n\t\treturn err\n\t}\n")
	fmt.Fprintf(&b, "\tindex := make(map[%s]int32, len(list))\n", t.KeyGoType())
	fmt.Fprintf(&b, "\tfor i := range list {\n")
	fmt.Fprintf(&b, "\t\tid := list[i].%s\n", t.KeyField().GoName)
	fmt.Fprintf(&b, "\t\tif _, dup := index[id]; dup {\n\t\t\treturn fmt.Errorf(\"%s: duplicate id %%v\", id)\n\t\t}\n", t.Name)
	fmt.Fprintf(&b, "\t\tindex[id] = int32(i)\n\t}\n")
	fmt.Fprintf(&b, "\tt.p.Store(&%s{list: list, index: index})\n", data)
	fmt.Fprintf(&b, "\treturn nil\n}\n\n")

	// Get
	fmt.Fprintf(&b, "// Get 按主键返回行，未命中返回 nil。\n")
	fmt.Fprintf(&b, "func (t *%sTable) Get(id %s) *%sRow {\n", name, t.KeyGoType(), name)
	fmt.Fprintf(&b, "\td := t.p.Load()\n")
	fmt.Fprintf(&b, "\tif d == nil {\n\t\treturn nil\n\t}\n")
	fmt.Fprintf(&b, "\ti, ok := d.index[id]\n")
	fmt.Fprintf(&b, "\tif !ok {\n\t\treturn nil\n\t}\n")
	fmt.Fprintf(&b, "\treturn &d.list[i]\n}\n\n")

	// List
	fmt.Fprintf(&b, "// List 返回全部行（按表顺序）。\n")
	fmt.Fprintf(&b, "func (t *%sTable) List() []%sRow {\n", name, name)
	fmt.Fprintf(&b, "\td := t.p.Load()\n")
	fmt.Fprintf(&b, "\tif d == nil {\n\t\treturn nil\n\t}\n")
	fmt.Fprintf(&b, "\treturn d.list\n}\n\n")

	// Len
	fmt.Fprintf(&b, "// Len 返回行数。\n")
	fmt.Fprintf(&b, "func (t *%sTable) Len() int {\n", name)
	fmt.Fprintf(&b, "\td := t.p.Load()\n")
	fmt.Fprintf(&b, "\tif d == nil {\n\t\treturn 0\n\t}\n")
	fmt.Fprintf(&b, "\treturn len(d.list)\n}\n\n")

	// 全局实例
	fmt.Fprintf(&b, "// %s 全局表实例，业务通过 %s.Get(id) 读取。\n", name, name)
	fmt.Fprintf(&b, "var %s = &%sTable{}\n\n", name, name)

	return format.Source([]byte(b.String()))
}

// emitRegistry 生成注册表：全部表实例列表。
func emitRegistry(tables []*Table) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by game/configs/gen; DO NOT EDIT.\n\n")
	b.WriteString("package configs\n\n")
	b.WriteString("// All 全部配置表，供 Manager 初始化与热更遍历。\n")
	b.WriteString("var All = []Table{\n")
	for _, t := range tables {
		fmt.Fprintf(&b, "\t%s,\n", t.StructName)
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}
